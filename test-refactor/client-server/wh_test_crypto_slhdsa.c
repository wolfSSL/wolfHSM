/* Drives the vector through the plain wolfCrypt API, which is how an
 * application reaches the server. */
static int _whTest_CryptoSlhDsaVerifyKat(int devId)
{
    int       ret;
    SlhDsaKey key[1];
    byte      msg[sizeof(whTestSlhDsaVerifyMsg)];
    byte      sig[WH_TEST_SLHDSA_KAT_SIG_LEN];

    memcpy(msg, whTestSlhDsaVerifyMsg, sizeof(msg));
    memcpy(sig, whTestSlhDsaVerifySig, sizeof(sig));

    ret = wc_SlhDsaKey_Init(key, WH_TEST_SLHDSA_KAT_PARAM, NULL, devId);
    if (ret != 0) {
        WH_ERROR_PRINT("Failed to initialize SLH-DSA key: %d\n", ret);
        return ret;
    }

    ret = wc_SlhDsaKey_ImportPublic(key, whTestSlhDsaVerifyPub,
                                    (word32)sizeof(whTestSlhDsaVerifyPub));
    if (ret != 0) {
        WH_ERROR_PRINT("Failed to import SLH-DSA public key: %d\n", ret);
    }

    if (ret == 0) {
        ret = wc_SlhDsaKey_Verify(key, NULL, 0, msg, (word32)sizeof(msg), sig,
                                  (word32)sizeof(sig));
        if (ret != 0) {
            WH_ERROR_PRINT("SLH-DSA vector did not verify: %d\n", ret);
        }
    }

    /* A changed message must not verify against the vector's signature. */
    if (ret == 0) {
        msg[0] ^= 1;
        if (wc_SlhDsaKey_Verify(key, NULL, 0, msg, (word32)sizeof(msg), sig,
                                (word32)sizeof(sig)) == 0) {
            WH_ERROR_PRINT("SLH-DSA verified a modified message\n");
            ret = WH_TEST_FAIL;
        }
        msg[0] ^= 1;
    }

    if (ret == 0) {
        sig[0] ^= 1;
        if (wc_SlhDsaKey_Verify(key, NULL, 0, msg, (word32)sizeof(msg), sig,
                                (word32)sizeof(sig)) == 0) {
            WH_ERROR_PRINT("SLH-DSA verified a modified signature\n");
            ret = WH_TEST_FAIL;
        }
        sig[0] ^= 1;
    }

    if (ret == 0) {
        WH_TEST_PRINT("SLH-DSA VERIFY KAT DEVID=0x%X SUCCESS\n", devId);
    }

    wc_SlhDsaKey_Free(key);
    return ret;
}

/* The same vector with the public key held by the server, which covers the
 * key import, export and lookup paths a verify-only build keeps. */
static int _whTest_CryptoSlhDsaVerifyKatCached(whClientContext* ctx)
{
    int       devId = WH_CLIENT_DEVID(ctx);
    int       ret;
    whKeyId   keyId = WH_KEYID_ERASED;
    SlhDsaKey key[1];
    SlhDsaKey handle[1];
    SlhDsaKey readback[1];
    int       keyInit      = 0;
    int       handleInit   = 0;
    int       readbackInit = 0;
    uint8_t   label[]      = "SlhDsaVerifyKat";
    byte      pub[WH_TEST_SLHDSA_KAT_PUB_LEN];
    word32    pubSz = sizeof(pub);

    ret = wc_SlhDsaKey_Init(key, WH_TEST_SLHDSA_KAT_PARAM, NULL, devId);
    if (ret != 0) {
        WH_ERROR_PRINT("Failed to initialize SLH-DSA key: %d\n", ret);
        return ret;
    }
    keyInit = 1;

    ret = wc_SlhDsaKey_ImportPublic(key, whTestSlhDsaVerifyPub,
                                    (word32)sizeof(whTestSlhDsaVerifyPub));
    if (ret != 0) {
        WH_ERROR_PRINT("Failed to import SLH-DSA public key: %d\n", ret);
        goto done;
    }

    ret = wh_Client_SlhDsaImportKey(ctx, key, &keyId,
                                    WH_NVM_FLAGS_USAGE_VERIFY, sizeof(label),
                                    label);
    if (ret != 0) {
        WH_ERROR_PRINT("Failed to cache the SLH-DSA public key: %d\n", ret);
        goto done;
    }

    ret = wc_SlhDsaKey_Init(readback, WH_TEST_SLHDSA_KAT_PARAM, NULL, devId);
    if (ret != 0) {
        WH_ERROR_PRINT("Failed to initialize SLH-DSA readback: %d\n", ret);
        goto done;
    }
    readbackInit = 1;

    ret = wh_Client_SlhDsaExportPublicKey(ctx, keyId, readback, 0, NULL);
    if (ret != 0) {
        WH_ERROR_PRINT("Failed to export the cached public key: %d\n", ret);
        goto done;
    }

    ret = wc_SlhDsaKey_ExportPublic(readback, pub, &pubSz);
    if (ret != 0) {
        WH_ERROR_PRINT("Failed to read back the public key: %d\n", ret);
        goto done;
    }
    if ((pubSz != sizeof(whTestSlhDsaVerifyPub)) ||
        (memcmp(pub, whTestSlhDsaVerifyPub, pubSz) != 0)) {
        WH_ERROR_PRINT("Cached SLH-DSA public key changed in transit\n");
        ret = WH_TEST_FAIL;
        goto done;
    }

    /* A bare handle: no key material, only the server key ID */
    ret = wc_SlhDsaKey_Init(handle, WH_TEST_SLHDSA_KAT_PARAM, NULL, devId);
    if (ret != 0) {
        WH_ERROR_PRINT("Failed to initialize SLH-DSA handle: %d\n", ret);
        goto done;
    }
    handleInit = 1;

    ret = wh_Client_SlhDsaSetKeyId(handle, keyId);
    if (ret != 0) {
        WH_ERROR_PRINT("Failed to set SLH-DSA key id: %d\n", ret);
        goto done;
    }

    ret = wc_SlhDsaKey_Verify(handle, NULL, 0, whTestSlhDsaVerifyMsg,
                              (word32)sizeof(whTestSlhDsaVerifyMsg),
                              whTestSlhDsaVerifySig,
                              (word32)sizeof(whTestSlhDsaVerifySig));
    if (ret != 0) {
        WH_ERROR_PRINT("Cached-key SLH-DSA verify failed: %d\n", ret);
        goto done;
    }

    {
        byte msg[sizeof(whTestSlhDsaVerifyMsg)];

        memcpy(msg, whTestSlhDsaVerifyMsg, sizeof(msg));
        msg[0] ^= 1;
        if (wc_SlhDsaKey_Verify(handle, NULL, 0, msg, (word32)sizeof(msg),
                                whTestSlhDsaVerifySig,
                                (word32)sizeof(whTestSlhDsaVerifySig)) == 0) {
            WH_ERROR_PRINT("Cached key verified a modified message\n");
            ret = WH_TEST_FAIL;
            goto done;
        }
    }

    WH_TEST_PRINT("SLH-DSA VERIFY KAT CACHED DEVID=0x%X SUCCESS\n", devId);
    ret = 0;

done:
    if (!WH_KEYID_ISERASED(keyId)) {
        (void)wh_Client_KeyEvict(ctx, keyId);
    }
    if (handleInit) {
        wc_SlhDsaKey_Free(handle);
    }
    if (readbackInit) {
        wc_SlhDsaKey_Free(readback);
    }
    if (keyInit) {
        wc_SlhDsaKey_Free(key);
    }
    return ret;
}

